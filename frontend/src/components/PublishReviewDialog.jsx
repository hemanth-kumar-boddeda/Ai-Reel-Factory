import { useEffect, useState } from 'react';
import api from '../utils/api';
import Button from './shared/Button';
import StatusBadge from './shared/StatusBadge';
import AuthenticatedVideo from './reel/AuthenticatedVideo';
import './PublishReviewDialog.css';

const ORIGIN_LABELS = {
  language_model: 'Written by a language model',
  protocol_stub: 'From a protocol stand-in, not a model',
  deterministic_composer: 'Composed deterministically, not written',
  mock_template: 'Mock placeholder content',
  unverified: 'Origin could not be verified',
};

const ASSET_LABELS = {
  image_model: 'Generated by an image model',
  placeholder: 'A placeholder, not a generated picture',
  branded_background: 'Branded backgrounds, not generated pictures',
};

const PRESENTER_LABELS = {
  voiceover: 'Voice-over, no presenter',
  synthetic_standin: 'A synthetic stand-in, not an animated presenter',
  avatar_provider: 'An animated presenter',
};

const OUTPUT_MODE_LABELS = {
  english_translation: 'English translation',
  telugu_script: 'Telugu script',
  tanglish: 'Tanglish',
  bilingual: 'Bilingual',
};

const SOURCE_MODE_LABELS = {
  auto: 'Automatic detection',
  te: 'Telugu speech',
  en: 'English speech',
  te_en: 'Telugu + English (code-switching)',
};

const TRANSLATION_ORIGIN_LABELS = {
  language_model: 'A hosted language model',
  local_model: 'A local open-source model',
  speech_translation: 'A local speech translation',
  passthrough: 'The original source text (not a translation)',
  mock: 'A placeholder (not a translation)',
  not_required: 'Not needed for this output mode',
};

function Fact({ label, value, tone }) {
  if (value === null || value === undefined || value === '') return null;
  return (
    <div className={`review-fact${tone ? ` review-fact-${tone}` : ''}`}>
      <span className="review-fact-label">{label}</span>
      <span className="review-fact-value">{value}</span>
    </div>
  );
}

/**
 * The review step before anything is published.
 *
 * It shows the rendered video, the caption, the source and the quality
 * report, and it only enables the publish button once the operator has
 * explicitly confirmed that they reviewed it.
 */
export default function PublishReviewDialog({ reelId, onClose, onPublished }) {
  const [report, setReport] = useState(null);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState(null);
  const [approved, setApproved] = useState(false);
  const [translationAcknowledged, setTranslationAcknowledged] = useState(false);
  const [publishing, setPublishing] = useState(false);
  const [outcome, setOutcome] = useState(null);
  const [publishError, setPublishError] = useState(null);

  useEffect(() => {
    let cancelled = false;
    setLoading(true);
    api
      .get(`/api/reels/${reelId}/publish-readiness`)
      .then((response) => {
        if (cancelled) return;
        setReport(response.data);
        setLoadError(null);
      })
      .catch((err) => {
        if (cancelled) return;
        setLoadError(
          err?.response?.data?.detail || err?.message || 'The review could not be loaded.'
        );
      })
      .finally(() => {
        if (!cancelled) setLoading(false);
      });
    return () => {
      cancelled = true;
    };
  }, [reelId]);

  const publish = async () => {
    setPublishing(true);
    setPublishError(null);
    try {
      const response = await api.post(`/api/reels/${reelId}/publish`);
      setOutcome(response.data);
      if (onPublished) onPublished(response.data);
    } catch (err) {
      setPublishError(
        err?.response?.data?.detail || err?.message || 'The Reel could not be submitted.'
      );
    } finally {
      setPublishing(false);
    }
  };

  const validationProblems = report?.validation?.problems || [];
  const blocked = !report?.can_publish;
  const review = report?.translation_review;
  const unresolved = review?.problems || [];
  // A translation with problems in it needs a second, explicit confirmation:
  // the operator has to say they looked at the unresolved lines.
  const needsTranslationConfirmation = unresolved.length > 0;
  const canPublish = approved && !needsTranslationConfirmation && !blocked && !publishing;

  return (
    <div className="review-backdrop" role="dialog" aria-modal="true" aria-label="Review before publishing">
      <div className="review-dialog">
        <header className="review-header">
          <h2>Review before publishing</h2>
          <button type="button" className="review-close" onClick={onClose} aria-label="Close">
            ×
          </button>
        </header>

        {loading && <p className="muted">Loading the review…</p>}
        {loadError && <p className="review-error">{loadError}</p>}

        {report && (
          <div className="review-body">
            <div className="review-preview">
              <AuthenticatedVideo
                reelId={reelId}
                className="review-video"
                controls
                data-testid="review-video"
              />
              <p className="review-caption-note">
                This is the exact file that will be published.
              </p>
            </div>

            <div className="review-details">
              <h3 className="review-title">{report.title}</h3>

              <Fact label="Status" value={<StatusBadge state={report.status} />} />
              <Fact
                label="QA score"
                value={report.qa_score != null ? Number(report.qa_score).toFixed(1) : null}
                tone={report.qa_score >= 70 ? 'good' : 'bad'}
              />
              <Fact label="Script written by" value={report.script_provider} />
              <Fact label="Script origin" value={ORIGIN_LABELS[report.content_origin] || report.content_origin} />
              <Fact label="Scene images" value={ASSET_LABELS[report.assets_origin] || report.assets_origin} />
              <Fact
                label="Presenter"
                value={
                  PRESENTER_LABELS[report.presenter_origin] ||
                  (report.presenter_lip_synced ? 'An animated presenter with lip sync' : null)
                }
              />
              <Fact label="Source" value={report.publisher} />
              <Fact
                label="Source URL"
                value={
                  report.source_url ? (
                    <a href={report.source_url} target="_blank" rel="noreferrer noopener">
                      {report.source_url}
                    </a>
                  ) : null
                }
              />
              <Fact label="Claims in the research" value={report.claims?.length || 0} />

              {review?.output_mode && (
                <div className="review-block">
                  <span className="review-fact-label">The captions</span>
                  <Fact
                    label="Caption language"
                    value={OUTPUT_MODE_LABELS[review.output_mode] || review.output_mode}
                  />
                  <Fact
                    label="Source language"
                    value={SOURCE_MODE_LABELS[review.source_mode] || review.source_mode}
                  />
                  <Fact
                    label="Where the text came from"
                    value={
                      TRANSLATION_ORIGIN_LABELS[review.origin] || review.origin
                    }
                    tone={review.has_unresolved ? 'bad' : 'good'}
                  />
                  {review.model && (
                    <Fact label="Model" value={`${review.provider}/${review.model}`} />
                  )}
                  {review.untranslated_count > 0 && (
                    <Fact
                      label="Untranslated lines"
                      value={review.untranslated_count}
                      tone="bad"
                    />
                  )}
                  {review.corrected_segments?.length > 0 && (
                    <Fact
                      label="Lines corrected by hand"
                      value={review.corrected_segments.length}
                    />
                  )}
                  {unresolved.length > 0 && (
                    <ul className="review-problems">
                      {unresolved.map((problem) => (
                        <li key={problem}>{problem}</li>
                      ))}
                    </ul>
                  )}
                  {review.warnings?.length > 0 && (
                    <ul className="review-problems">
                      {review.warnings.map((warning) => (
                        <li key={warning}>{warning}</li>
                      ))}
                    </ul>
                  )}
                </div>
              )}

              <div className="review-block">
                <span className="review-fact-label">The caption that will be posted</span>
                <pre className="review-caption">{report.caption || '(no caption)'}</pre>
                {report.hashtags?.length > 0 && (
                  <p className="review-hashtags">{report.hashtags.join(' ')}</p>
                )}
              </div>

              {(report.qa_checks || []).length > 0 && (
                <div className="review-block">
                  <span className="review-fact-label">The quality report</span>
                  <ul className="review-checks">
                    {report.qa_checks.map((check, index) => (
                      <li key={`${check.name}-${index}`} className={check.passed ? 'ok' : 'bad'}>
                        <span className="review-check-name">{check.name}</span>
                        <span className="review-check-message">{check.message}</span>
                      </li>
                    ))}
                  </ul>
                </div>
              )}

              <div className="review-block">
                <span className="review-fact-label">The Instagram account</span>
                {report.connected ? (
                  <p className="review-connected">Connected as {report.account_id}.</p>
                ) : (
                  <p className="review-error">No Instagram account is connected.</p>
                )}
                {validationProblems.length > 0 && (
                  <ul className="review-problems">
                    {validationProblems.map((problem) => (
                      <li key={problem}>{problem}</li>
                    ))}
                  </ul>
                )}
                {!report.public_base_url && (
                  <p className="review-error">
                    The public media URL is not set, so Instagram cannot download the video.
                  </p>
                )}
                {report.auto_publish_enabled && (
                  <p className="review-warn">
                    Automatic publishing is on for this deployment. This approval still
                    governs this Reel.
                  </p>
                )}
              </div>

              {report.last_publication && (
                <div className="review-block">
                  <span className="review-fact-label">The last publication attempt</span>
                  <p>
                    Status {report.last_publication.status}
                    {report.last_publication.error_kind
                      ? ` (${report.last_publication.error_kind})`
                      : ''}
                    {report.last_publication.retry_count
                      ? ` (attempt ${report.last_publication.retry_count})`
                      : ''}
                  </p>
                  {report.last_publication.published_media_id && (
                    <p>
                      Media id <code>{report.last_publication.published_media_id}</code>
                    </p>
                  )}
                  {report.last_publication.permalink && (
                    <p>
                      <a
                        href={report.last_publication.permalink}
                        target="_blank"
                        rel="noreferrer noopener"
                      >
                        {report.last_publication.permalink}
                      </a>
                    </p>
                  )}
                  {report.last_publication.error_message && (
                    <p className="review-error">{report.last_publication.error_message}</p>
                  )}
                </div>
              )}
            </div>
          </div>
        )}

        {outcome && (
          <div className="review-outcome">
            <p>
              The Reel was submitted as publishing {outcome.publishing_id}. It is only
              marked published once Instagram confirms it.
            </p>
          </div>
        )}
        {publishError && <p className="review-error">{publishError}</p>}

        <footer className="review-footer">
          <label className="review-approval">
            <input
              type="checkbox"
              checked={approved}
              onChange={(event) => setApproved(event.target.checked)}
              disabled={blocked || publishing}
              data-testid="review-approval"
            />
            <span>
              I have watched the video above and approve publishing it to Instagram.
            </span>
          </label>
          {needsTranslationConfirmation && (
            <label className="review-approval review-approval-warning">
              <input
                type="checkbox"
                checked={translationAcknowledged}
                onChange={(event) => setTranslationAcknowledged(event.target.checked)}
                disabled={publishing}
                data-testid="review-translation-acknowledged"
              />
              <span>
                I have read the unresolved translation problems above ({unresolved.length}{' '}
                {unresolved.length === 1 ? 'problem' : 'problems'}) and I am publishing
                this Reel anyway.
              </span>
            </label>
          )}
          {blocked && report?.reason && (
            <p className="review-error" data-testid="review-blocked">
              It cannot be published yet: {report.reason}
            </p>
          )}
          <div className="review-actions">
            <Button variant="ghost" onClick={onClose} disabled={publishing}>
              Cancel
            </Button>
            <Button
              onClick={publish}
              disabled={!canPublish}
              data-testid="review-publish"
            >
              {publishing ? 'Submitting…' : 'Publish to Instagram'}
            </Button>
          </div>
        </footer>
      </div>
    </div>
  );
}
